// Vercel buildCommand for the backend service.
//
// WHY THIS EXISTS
// ---------------
// Vercel failed every request to the backend with:
//
//   No exports found in module "/var/task/backend/index.cjs"
//   Did you forget to export a function or a server?
//
// That message means the built function exported nothing, which only happens
// when the builder saw an empty or unrecognised entrypoint. Vercel's Express
// builder picks the entrypoint by reading each candidate file from disk and
// testing it against /(?:from|require|import)\s*\(?\s*["']express["']/ , then
// re-reading it again after the build command runs
// (packages/express/src/build.ts, checkMatchesRegex).
//
// This script removes every way that check can fail: it writes a small,
// self-contained express entrypoint to backend/index.js at build time. The
// file always imports express, always exports the app, and is never empty, so
// whichever candidate Vercel inspects is valid.
//
// The real application still lives in ./Server/app and is imported here; this
// only replaces the thin entry shim.

const fs = require('fs');
const path = require('path');

const target = path.join(__dirname, 'index.js');

const contents = `// GENERATED by build.js for the Vercel build. Do not edit by hand.
//
// Vercel owns the HTTP listener, so this file exports the Express app instead
// of binding a port. Local development uses server.js, which adds Socket.IO and
// binds the port itself.
const express = require('express');
void express;

require('dotenv').config({ path: require('path').join(__dirname, '.env') });

const app = require('./Server/app');

module.exports = app;
`;

fs.writeFileSync(target, contents);
console.log(`[build] wrote ${target} (${Buffer.byteLength(contents)} bytes)`);
